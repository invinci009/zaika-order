/**
 * Find matching image for item by direct name or keyword match
 */
export function getFoodImage(name: string, categoryId?: string): string | null {
  const lower = name.toLowerCase().trim()
  if (FOOD_IMAGE_MAP[lower]) return FOOD_IMAGE_MAP[lower]

  // Partial match
  for (const [key, url] of Object.entries(FOOD_IMAGE_MAP)) {
    if (lower.includes(key) || key.includes(lower)) {
      return url
    }
  }

  // Fallback by cuisine category keywords
  if (lower.includes('biryani') || lower.includes('handi')) return FOOD_IMAGE_MAP['chicken biryani']
  if (lower.includes('tandoori') || lower.includes('tikka') || lower.includes('kabab')) return FOOD_IMAGE_MAP['chicken tandoori']
  if (lower.includes('paneer')) return FOOD_IMAGE_MAP['paneer butter masala']
  if (lower.includes('noodles')) return FOOD_IMAGE_MAP['veg noodles']
  if (lower.includes('soup')) return FOOD_IMAGE_MAP['veg manchow']
  if (lower.includes('naan') || lower.includes('roti') || lower.includes('kulcha')) return FOOD_IMAGE_MAP['butter naan']
  if (lower.includes('lollypop') || lower.includes('chilli') || lower.includes('fry') || lower.includes('manchurian')) {
    return lower.includes('chicken') ? FOOD_IMAGE_MAP['chicken lollypop'] : FOOD_IMAGE_MAP['mix veg. manchurian dry']
  }
  if (lower.includes('curry') || lower.includes('masala') || lower.includes('kadhai') || lower.includes('handi')) {
    return lower.includes('chicken') ? FOOD_IMAGE_MAP['chicken butter masala'] : FOOD_IMAGE_MAP['paneer butter masala']
  }

  return null
}
