/**
 * Returns a high-resolution, unique appetizing image for each dish.
 * Normalizes dish name by removing punctuation and extra spaces.
 */
export function getFoodImage(name: string, categoryId?: string): string | null {
  const clean = name.toLowerCase().replace(/[^a-z0-9]/g, ' ').replace(/\s+/g, ' ').trim()

  // 1. Direct or normalized match
  if (FOOD_IMAGE_MAP[clean]) return FOOD_IMAGE_MAP[clean]

  // 2. Substring match
  for (const [key, url] of Object.entries(FOOD_IMAGE_MAP)) {
    const keyClean = key.replace(/[^a-z0-9]/g, ' ').replace(/\s+/g, ' ').trim()
    if (clean === keyClean || clean.includes(keyClean) || keyClean.includes(clean)) {
      return url
    }
  }

  // 3. Category-safe keyword match
  if (clean.includes('sweet corn') && clean.includes('non veg')) return FOOD_IMAGE_MAP['sweet corn (non veg)']
  if (clean.includes('sweet corn')) return FOOD_IMAGE_MAP['veg sweet corn']
  if (clean.includes('hot n sour') && (clean.includes('non veg') || clean.includes('chicken'))) return FOOD_IMAGE_MAP['hot n sour (non veg)']
  if (clean.includes('hot n sour')) return FOOD_IMAGE_MAP['hot n sour (veg)']
  if (clean.includes('chicken') && clean.includes('manchow')) return FOOD_IMAGE_MAP['chicken manchow soup']
  if (clean.includes('manchow')) return FOOD_IMAGE_MAP['veg manchow']
  if (clean.includes('chicken') && clean.includes('mushroom')) return FOOD_IMAGE_MAP['chicken mushroom soup']
  if (clean.includes('mushroom')) return FOOD_IMAGE_MAP['mushroom soup']

  if (clean.includes('biryani') && clean.includes('mutton')) return FOOD_IMAGE_MAP['mutton biryani']
  if (clean.includes('biryani')) return FOOD_IMAGE_MAP['chicken biryani']
  if (clean.includes('tandoori') && !clean.includes('roti')) return FOOD_IMAGE_MAP['chicken tandoori']
  if (clean.includes('lollypop')) return FOOD_IMAGE_MAP['chicken lollypop']
  if (clean.includes('butter masala')) return FOOD_IMAGE_MAP['chicken butter masala']
  if (clean.includes('tikka')) return FOOD_IMAGE_MAP['chicken tikka']
  if (clean.includes('french fry') || clean.includes('french fries')) return FOOD_IMAGE_MAP['french fry']
  if (clean.includes('peanut') || clean.includes('penut')) return FOOD_IMAGE_MAP['penuts masala']
  if (clean.includes('kulcha')) return FOOD_IMAGE_MAP['kulcha']
  if (clean.includes('paneer') && clean.includes('naan')) return FOOD_IMAGE_MAP['paneer garlic naan']
  if (clean.includes('garlic') && clean.includes('naan')) return FOOD_IMAGE_MAP['garlic naan']
  if (clean.includes('plain') && clean.includes('naan')) return FOOD_IMAGE_MAP['plain naan']
  if (clean.includes('naan') || clean.includes('roti')) return FOOD_IMAGE_MAP['butter naan']
  if (clean.includes('noodle')) return FOOD_IMAGE_MAP['veg noodles']
  if (clean.includes('paneer')) return FOOD_IMAGE_MAP['paneer butter masala']

  return null
}
